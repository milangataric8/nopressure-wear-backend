package rs.nopressurewear.media.internal.storage;

import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.context.annotation.Profile;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;
import rs.nopressurewear.media.internal.application.RemoveBgService;
import rs.nopressurewear.media.internal.config.S3Properties;
import software.amazon.awssdk.core.sync.RequestBody;
import software.amazon.awssdk.services.s3.S3Client;
import software.amazon.awssdk.services.s3.model.DeleteObjectRequest;
import software.amazon.awssdk.services.s3.model.PutObjectRequest;
import software.amazon.awssdk.services.s3.model.S3Exception;

import java.net.URI;
import java.util.Locale;
import java.util.UUID;

@Service
@Profile("prod")
@ConditionalOnProperty(name = "app.storage.s3-enabled", havingValue = "true")
@RequiredArgsConstructor
@Slf4j
public class S3StorageService implements StorageProvider {
    private final S3Client s3Client;
    private final S3Properties properties;
    private final RemoveBgService removeBgService;

    @Override
    public String store(MultipartFile file, boolean removeBg) {
        try {
            boolean processed = removeBg && removeBgService.isEnabled();
            byte[] bytes = processed ? removeBgService.removeBackground(file) : file.getBytes();
            String contentType = processed ? "image/png" : file.getContentType();
            if (contentType == null || contentType.isBlank()) contentType = "application/octet-stream";
            String key = (properties.prefix().isEmpty() ? "" : properties.prefix() + "/")
                    + UUID.randomUUID() + "." + (processed ? "png" : extension(file.getOriginalFilename()));
            s3Client.putObject(PutObjectRequest.builder()
                            .bucket(properties.bucket()).key(key).contentType(contentType).build(),
                    RequestBody.fromBytes(bytes));
            return properties.publicBaseUrl() + "/" + key;
        } catch (Exception e) {
            logFailure("store", e);
            throw new IllegalStateException("S3 media upload failed", e);
        }
    }

    private String extension(String filename) {
        if (filename == null) return "bin";
        int dot = filename.lastIndexOf('.');
        String extension = dot >= 0 ? filename.substring(dot + 1).toLowerCase(Locale.ROOT) : "";
        return extension.matches("[a-z0-9]{1,10}") ? extension : "bin";
    }

    @Override
    public void delete(String url) {
        String key = ownedKey(url);
        if (key == null) return;
        try {
            s3Client.deleteObject(DeleteObjectRequest.builder().bucket(properties.bucket()).key(key).build());
        } catch (Exception e) {
            logFailure("delete", e);
        }
    }

    private String ownedKey(String url) {
        if (url == null) return null;
        try {
            URI base = URI.create(properties.publicBaseUrl());
            URI candidate = URI.create(url);
            if (!base.getScheme().equalsIgnoreCase(candidate.getScheme())
                    || !base.getHost().equalsIgnoreCase(candidate.getHost())
                    || base.getPort() != candidate.getPort() || candidate.getRawUserInfo() != null
                    || candidate.getRawQuery() != null || candidate.getRawFragment() != null) return null;
            String basePath = base.getRawPath() + "/";
            String path = candidate.getRawPath();
            if (path == null || !path.startsWith(basePath)) return null;
            String key = path.substring(basePath.length());
            String prefix = properties.prefix().isEmpty() ? "" : properties.prefix() + "/";
            // Only keys generated by this provider; excludes foreign URLs, traversal and encoded paths.
            if (!key.startsWith(prefix)) return null;
            String objectName = key.substring(prefix.length());
            if (!objectName.matches("[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\\.[a-z0-9]{1,10}")) return null;
            return key;
        } catch (IllegalArgumentException e) {
            return null;
        }
    }

    private void logFailure(String operation, Exception exception) {
        // Do not log raw exception text, request URLs or stack traces: SDK/client errors may contain secrets.
        if (exception instanceof S3Exception s3) {
            String errorCode = s3.awsErrorDetails() == null ? "unknown" : s3.awsErrorDetails().errorCode();
            log.warn("Media storage provider=S3 operation={} exception={} status={} reason={}",
                    operation, exception.getClass().getSimpleName(), s3.statusCode(), safeCode(errorCode));
        } else {
            log.warn("Media storage provider=S3 operation={} exception={} reason=client_or_processing_failure",
                    operation, exception.getClass().getSimpleName());
        }
    }

    private String safeCode(String code) {
        return code != null && code.matches("[A-Za-z0-9_.-]{1,80}") ? code : "unknown";
    }
}
